primeiroNumero = float(input("Digite um número : "))
segundoNumero = float(input("Digite outro número : "))

if(segundoNumero % 2 == 0): #Se o número for dividido por 2 restar 0 é par
    print(segundoNumero, "é par")
else:
    print(segundoNumero, "é ímpar")

if(primeiroNumero % 2 == 0): #Se o número for dividido por 2 restar 0 é par
    print(primeiroNumero, "é par")
else:
    print(primeiroNumero, "é ímpar")